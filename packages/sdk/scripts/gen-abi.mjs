#!/usr/bin/env node
/**
 * Generates typed ABI modules from Foundry build output.
 * Run after any contract change: `forge build` in packages/contracts, then `pnpm --filter @wealthkart/sdk gen`.
 * Output is committed so the web build doesn't need Foundry.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "..", "contracts", "out");
const target = join(here, "..", "src", "abi");
const CONTRACTS = ["CircleVault", "CircleFactory", "Reputation"];
/**
 * Linked libraries whose events and errors surface through a contract (ADR 0031). The vault
 * delegatecalls them, so their logs and reverts come from the vault's address; viem needs them
 * in the vault's ABI to decode them.
 */
const MERGE = { CircleVault: ["Membership", "Rules", "Governance", "Exits"] };

const read = (name) =>
  JSON.parse(readFileSync(join(outDir, `${name}.sol`, `${name}.json`), "utf8"));
const sig = (e) => `${e.type}:${e.name}(${(e.inputs ?? []).map((i) => i.type).join(",")})`;

mkdirSync(target, { recursive: true });
const index = [];
for (const name of CONTRACTS) {
  const artifact = read(name);
  const seen = new Set(artifact.abi.map(sig));
  for (const lib of MERGE[name] ?? []) {
    for (const entry of read(lib).abi) {
      if ((entry.type === "event" || entry.type === "error") && !seen.has(sig(entry))) {
        seen.add(sig(entry));
        artifact.abi.push(entry);
      }
    }
  }
  const constName = `${name.charAt(0).toLowerCase()}${name.slice(1)}Abi`;
  const body =
    `// Generated by scripts/gen-abi.mjs from packages/contracts. Do not edit by hand.\n` +
    `export const ${constName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(target, `${name}.ts`), body);
  index.push(`export { ${constName} } from "./${name}.js";`);
  console.log(`wrote src/abi/${name}.ts (${artifact.abi.length} entries)`);
}
writeFileSync(join(target, "index.ts"), index.join("\n") + "\n");
